              xmsg = '*** ACM fails ***'
              call m3exit(pname, mdate, mtime, xmsg, xstat2)
              !WRITE(*,*) 'in vdiff_bwd, after CALL m3exit'
              !WRITE(*,*) 'cngrd_bwd: ', cngrd_bwd(7,1,1:4,1:4) !cl3293
              !WRITE(*,*) 'cngrd_bwd: ', cngrd_bwd(8,1,1:4,1:4) !cl3293
            endif
            if ( ( fnl .le. 0.0 ) .or.            ! never gonna happen for CONVCT
     &           ( lcbl .ge. nlays-1 ) .or.       ! .GT. never gonna happen
     &           ( hol( c,r ) .gt. -0.00001 ) )   ! never gonna happen
     &         WRITE(logdev, '(a, i3, 1x, 5(1pe13.5))')
     &           ' LCBL, MBAR, FNL, SEDDY1, HOL:',
     &           lcbl, mbar, fnl, eddyv(c,r,1), seddy(1,c,r), hol(c,r)
            do l = 1, lcbl-1
              mbarks(l) = mbar
              mdwn(l) = mbar*(xpbl(c,r)-x3face_gd(l-1))*rdx3f(l)
            end do
            mbarks(lcbl) = mbar*(xpbl(c,r)-x3face_gd(lcbl-1))*rdx3f(lcbl)
            mdwn(lcbl) = mbarks(lcbl)
            rz = (x3face_gd(lcbl)-x3face_gd(1))*rdx3f(1)
            dtacm = 1./(mbar*rz)
            dtlim = min(0.75*dtacm,dtlim)
          else
            lcbl = 1
          endif
          
          nlp = int(dtsec/dtlim+0.99)
          dts = dtsec/nlp
          do l = 1, nlays
            eddy(l) = seddy(l,c,r)
          end do
          do v = 1, ndepv_spc
            depvcr(v) = depv(v,c,r)
            efac1(v) = exp(-(depvcr(v)*rdepvht(c,r)*thbar*dts))
            efac2(v) = exp(-(depvcr(v)*rdepvht(c,r)*theta*dts))
            !WRITE(*,*) 'in vdiff_bwd, after efac2(v) = '
            !WRITE(*,*) 'ndepv_spc: ', ndepv_spc !cl3293
            !WRITE(*,*) 'v: ', v !cl3293
            !WRITE(*,*) 'efac2(v): ', efac2(v) !cl3293
            !WRITE(*,*) 'depvcr(v): ', depvcr(v) !cl3293
            !WRITE(*,*) 'depv(v,c,r): ', depv(v,c,r) !cl3293
          end do
          pol(nh3_so2) = pvdd(nh3_so2,c,r)/depvcr(nh3_hit)
          pol(nh3_nh3) = pvdd(nh3_nh3,c,r)/depvcr(nh3_hit)
          !pol(hono_no2) = pvdd(hono_no2,c,r)/depvcr(hono_hit) !cl3293
          do l = 1, nlays
            do v = 1, n_spc_diff
              conc_bwd(v,l) = conc_bwd(v,l)+cngrd_bwd(diff_map(v),l,c,r)
              !WRITE(*,*) 'in vdiff_bwd, after conc_bwd(v,l) = conc_bwd(v,l)+cngrd_bwd(diff_map(v),l,c,r)'
              !WRITE(*,*) 'l: ', l !cl3293
              !WRITE(*,*) 'v: ', v !cl3293
              !WRITE(*,*) 'conc_bwd(v,l): ', conc_bwd(v,l) !cl3293
              !WRITE(*,*) 'diff_map(v): ', diff_map(v) !cl3293
              !WRITE(*,*) 'cngrd_bwd(diff_map(v),l,c,r): ', cngrd_bwd(diff_map(v),l,c,r) !cl3293
              cngrd_bwd(diff_map(v),l,c,r) = 0.
            end do
          end do
          do nl = nlp, 1, -1
            do l = 1, nlays
              aa(l) = 0.
              bb(l) = 0.
              cc(l) = 0.
              ee(l) = 0.
            end do
            if (convct(c,r)) then
              do l = 2, lcbl
                aa(l) = -(crankp*mbarks(l)*dts)
                bb(l) = 1.+crankp*mdwn(l)*dts
                ee(l-1) = -(crankp*mdwn(l)*dts*dx3f(l)*rdx3f(l-1))
              end do
            endif
            aa(2) = aa(2)-eddy(1)*crankp*rdx3f(2)*dts
            ee(1) = ee(1)-eddy(1)*crankp*rdx3f(1)*dts
            do l = 2, nlays
              if (l .gt. lcbl) then
                bb(l) = 1.
              endif
              xplus = eddy(l)*rdx3f(l)*dts
              xminus = eddy(l-1)*rdx3f(l)*dts
              bb(l) = bb(l)+(xplus+xminus)*crankp
              cc(l) = -(xminus*crankp)
              ee(l) = ee(l)-xplus*crankp
            end do
            bb(1) = 1.
            if (convct(c,r)) then
              lfac1 = (xpbl(c,r)-x3face_gd(1))*rdx3f(1)*dts
              bb(1) = bb(1)+crankp*mbarks(1)*lfac1
            endif
            bb(1) = bb(1)+crankp*eddy(1)*rdx3f(1)*dts
            lfac1 = crankq*eddy(1)*rdx3f(1)*dts
            do v = ndepv_spc, 1, -1
              if (v .eq. hono_hit) then
                !conc_no2b = pol(hono_no2)*(1.0-efac2(v))*conc_bwd(hono_map,1) !cl3293
                conc_bwd(hono_map,1) = conc_bwd(hono_map,1)*efac2(v)
                !WRITE(*,*) 'in vdiff_bwd, after if (v .eq. hono_hit) then'
                !WRITE(*,*) 'v: ', v !cl3293
                !WRITE(*,*) 'conc_bwd(hono_map,1): ', conc_bwd(hono_map,1) !cl3293
                !WRITE(*,*) 'hono_map: ', hono_map !cl3293
                !WRITE(*,*) 'efac2(v): ', efac2(v) !cl3293
              else if (v .eq. hno3_hit) then
                conc_bwd(hno3_map,1) = conc_bwd(hno3_map,1)*efac2(v)
                !WRITE(*,*) 'in vdiff_bwd, after else if (v .eq. hno3_hit) then'
                !WRITE(*,*) 'v: ', v !cl3293
                !WRITE(*,*) 'conc_bwd(hno3_map,1): ', conc_bwd(hno3_map,1) !cl3293
                !WRITE(*,*) 'hno3_map: ', hno3_map !cl3293
                !WRITE(*,*) 'efac2(v): ', efac2(v) !cl3293                
              else if (v .eq. no2_hit) then
                conc_bwd(no2_map,1) = conc_bwd(no2_map,1)*efac2(v)
                !WRITE(*,*) 'in vdiff_bwd, after  else if (v .eq. no2_hit) then'
                !WRITE(*,*) 'v: ', v !cl3293
                !WRITE(*,*) 'conc_bwd(no2_map,1): ', conc_bwd(no2_map,1) !cl3293
                !WRITE(*,*) 'no2_map: ', no2_map !cl3293
                !WRITE(*,*) 'efac2(v): ', efac2(v) !cl3293        
              else if (v .eq. nh3_hit) then
                conc_so2b = pol(nh3_so2)*(1.0-efac2(v))*conc_bwd(nh3_map,1)
                conc_bwd(nh3_map,1) =
     &               pol(nh3_nh3)*(1.0-efac2(v))*conc_bwd(nh3_map,1)
     &               +conc_bwd(nh3_map,1)*efac2(v)
                !WRITE(*,*) 'in vdiff_bwd, after else if (v .eq. nh3_hit) then'
                !WRITE(*,*) 'v: ', v !cl3293
                !WRITE(*,*) 'conc_bwd(nh3_map,1): ', conc_bwd(nh3_map,1) !cl3293
                !WRITE(*,*) 'nh3_map: ', nh3_map !cl3293
                !WRITE(*,*) 'efac2(v): ', efac2(v) !cl3293        
              else if (v .eq. so2_hit) then
                conc_bwd(so2_map,1) = conc_bwd(so2_map,1)*efac2(v)
                !WRITE(*,*) 'in vdiff_bwd, after else if (v .eq. so2_hit) then'
                !WRITE(*,*) 'v: ', v !cl3293
                !WRITE(*,*) 'conc_bwd(so2_map,1): ', conc_bwd(so2_map,1) !cl3293
                !WRITE(*,*) 'so2_map: ', so2_map !cl3293
                !WRITE(*,*) 'efac2(v): ', efac2(v) !cl3293        
              else
                conc_bwd(dv2df(v),1) = conc_bwd(dv2df(v),1)*efac2(v)
                !WRITE(*,*) 'in vdiff_bwd, after else'
                !WRITE(*,*) 'v: ', v !cl3293
                !WRITE(*,*) 'conc_bwd(dv2df(v),1): ', conc_bwd(dv2df(v),1) !cl3293
                !WRITE(*,*) 'dv2df(v): ', dv2df(v) !cl3293
                !WRITE(*,*) 'efac2(v): ', efac2(v) !cl3293        
              endif
            end do
            !conc_bwd(no2_map,1) = conc_bwd(no2_map,1) + conc_no2b
            !conc_bwd(so2_map,1) = conc_bwd(so2_map,1) + conc_so2b
            !WRITE(*,*) 'in vdiff_bwd, after end do'
            !WRITE(*,*) 'conc_bwd(no2_map,1): ', conc_bwd(no2_map,1) !cl3293
            !WRITE(*,*) 'conc_bwd(so2_map,1): ', conc_bwd(so2_map,1) !cl3293
            !WRITE(*,*) 'no2_map: ', no2_map !cl3293
            !WRITE(*,*) 'so2_map: ', so2_map !cl3293       
            do l = 1, nlays
              do v = 1, n_spc_diff
                uu_bwd(v,l) = uu_bwd(v,l)+conc_bwd(v,l)
                !WRITE(*,*) 'l: ', l !cl3293
                !WRITE(*,*) 'v: ', v !cl3293
                !WRITE(*,*) 'conc_bwd(v,l): ', conc_bwd(v,l) !cl3293
                !WRITE(*,*) 'uu_bwd(v,l): ', uu_bwd(v,l) !cl3293
                conc_bwd(v,l) = 0.
              end do
            end do
            if (convct(c,r)) then
              call matrix_bwd( aa,bb,cc,ee,dd_bwd,uu_bwd )
              !WRITE(*,*) 'in vdiff_bwd, after CALL matrix_bwd'
              !WRITE(*,*) 'cngrd_bwd: ', cngrd_bwd(7,1,1:4,1:4) !cl3293
              !WRITE(*,*) 'cngrd_bwd: ', cngrd_bwd(8,1,1:4,1:4) !cl3293
            else
              call tri_bwd( cc,bb,ee,dd_bwd,uu_bwd )
              !WRITE(*,*) 'in vdiff_bwd, after CALL tri_bwd'
              !WRITE(*,*) 'r: ', r !cl3293
              !WRITE(*,*) 'c: ', c !cl3293
              !WRITE(*,*) 'l: ', l !cl3293
              !WRITE(*,*) 'v: ', v !cl3293
              !WRITE(*,*) 'cc: ', cc !cl3293
              !WRITE(*,*) 'bb: ', bb !cl3293
              !WRITE(*,*) 'ee: ', ee !cl3293
              !WRITE(*,*) 'dd_bwd: ', dd_bwd !cl3293
              !WRITE(*,*) 'dd_bwd.shape: ', shape(dd_bwd) !cl3293
              !WRITE(*,*) 'uu_bwd: ', uu_bwd !cl3293
              !WRITE(*,*) 'n_spc_diff: ', n_spc_diff !cl3293

              !WRITE(*,*) 'cngrd_bwd: ', cngrd_bwd(7,1,1:4,1:4) !cl3293
              !WRITE(*,*) 'cngrd_bwd: ', cngrd_bwd(8,1,1:4,1:4) !cl3293
            endif
            do v = 1, n_spc_diff
              conc_em_bwd(v,1) = conc_em_bwd(v,1) + dd_bwd(v,1)
              conc_bwd(v,2) = conc_bwd(v,2)+dd_bwd(v,1)*lfac1
              conc_bwd(v,1) = conc_bwd(v,1)-dd_bwd(v,1)*lfac1
            end do
            if (convct(c,r)) then
              lfac1 = (xpbl(c,r)-x3face_gd(1))*rdx3f(1)*dts
              lfac2 = crankq*mdwn(2)*dx3f(2)*rdx3f(1)*dts
              lfac1 = crankq*mbarks(1)*lfac1
              do v = 1, n_spc_diff
                conc_bwd(v,2) = conc_bwd(v,2)+dd_bwd(v,1)*lfac2
                conc_bwd(v,1) = conc_bwd(v,1)-dd_bwd(v,1)*lfac1
              end do
            endif
            do v = 1, n_spc_diff
              conc_bwd(v,1) = conc_bwd(v,1)+dd_bwd(v,1)
              dd_bwd(v,1) = 0.
            end do
            do l = 2, nlays
              xplus = eddy(l)*rdx3f(l)*dts
              xminus = eddy(l-1)*rdx3f(l)*dts
              if (l .eq. nlays) then
                do v = 1, n_spc_diff
                  conc_bwd(v,l-1) = conc_bwd(v,l-1)+dd_bwd(v,l)*crankq*xminus
                  conc_bwd(v,l) = conc_bwd(v,l)-dd_bwd(v,l)*crankq*xminus
                end do
              else
                lfac1 = crankq*xplus
                lfac2 = crankq*xminus
                do v = 1, n_spc_diff
                  conc_bwd(v,l-1) = conc_bwd(v,l-1)+dd_bwd(v,l)*lfac2
                  conc_bwd(v,l+1) = conc_bwd(v,l+1)+dd_bwd(v,l)*lfac1
                  conc_bwd(v,l) = conc_bwd(v,l)-dd_bwd(v,l)*(lfac1+lfac2)
                  if ( l .le. emlays ) then
                    conc_em_bwd(v,l) = conc_em_bwd(v,l) +  dd_bwd(v,l)
                  end if
                end do
              endif
              if (l .gt. lcbl) then
                do v = 1, n_spc_diff
                  conc_bwd(v,l) = conc_bwd(v,l)+dd_bwd(v,l)
                  dd_bwd(v,l) = 0.
                end do
              endif
            end do
            if (convct(c,r)) then
              do l = 2, lcbl
                delc_bwd = 0.
                mfac = dx3f(l+1)*rdx3f(l)*mdwn(l+1)
                do v = 1, n_spc_diff
                  delc_bwd = 0.
                  conc_bwd(v,l) = conc_bwd(v,l)+dd_bwd(v,l)
                  delc_bwd = delc_bwd+dd_bwd(v,l)*crankq
                  dd_bwd(v,l) = 0.
                  conc_bwd(v,l+1) = conc_bwd(v,l+1)+delc_bwd*dts*mfac
                  conc_bwd(v,l) = conc_bwd(v,l)-delc_bwd*dts*mdwn(l)
                  conc_bwd(v,1) = conc_bwd(v,1)+delc_bwd*dts*mbarks(l)
                  delc_bwd = 0.
                end do
              end do
            endif
            do l = 1, nlays
              do v = 1, n_spc_diff
                dd_bwd(v,l) = 0.
              end do
            end do
            do v = ndepv_spc, 1, -1
              if (v .eq. hono_hit) then
                !conc_no2b = pol(hono_no2)*(1.0-efac1(v))*conc_bwd(hono_map,1)
                conc_bwd(hono_map,1) = conc_bwd(hono_map,1)*efac1(v)
              else if (v .eq. hno3_hit) then
                conc_bwd(hno3_map,1) = conc_bwd(hno3_map,1)*efac1(v)
              else if (v .eq. no2_hit) then
                conc_bwd(no2_map,1) = conc_bwd(no2_map,1)*efac1(v)
              else if (v .eq. nh3_hit) then
                conc_so2b = pol(nh3_so2)*(1.0-efac1(v))*conc_bwd(nh3_map,1)
                conc_bwd(nh3_map,1) =
     &               pol(nh3_nh3)*(1.0-efac1(v))*conc_bwd(nh3_map,1)
     &               +conc_bwd(nh3_map,1)*efac1(v)
              else if (v .eq. so2_hit) then
                conc_bwd(so2_map,1) = conc_bwd(so2_map,1)*efac1(v)
              else
                conc_bwd(dv2df(v),1) = conc_bwd(dv2df(v),1)*efac1(v)
              endif
            end do
            !conc_bwd(no2_map,1) = conc_bwd(no2_map,1) + conc_no2b
            !conc_bwd(so2_map,1) = conc_bwd(so2_map,1) + conc_so2b
          end do

          vdemisb (:,:,c,r) = 0.0
          do l = 1, emlays
            do v = 1, n_spc_diff
              vdemisb(df2em(v), l, c, r) = vdemisb(df2em(v), l, c, r) + dts*conc_em_bwd(v, l)
              conc_em_bwd(v, l) = 0.0
            end do
          end do

          do l = 1, nlays
            do v = 1, n_spc_diff
              cngrd_bwd(diff_map(v),l,c,r) = cngrd_bwd(diff_map(v),l,c,r)+conc_bwd(v,l)
              conc_bwd(v,l) = 0.
            end do
          end do
        end do
      end do

!slz sens to emis
      call  get_emis_b ( jdate, jtime, convpa,
     &                   rdx3f, rrhoj, rjacm, vdemisb, cgrid_em_bwd)
      !WRITE(*,*) 'in vdiff_bwd, after CALL get_emis_b'
      !WRITE(*,*) 'cngrd_bwd: ', cngrd_bwd(7,1,1:4,1:4) !cl3293
      !WRITE(*,*) 'cngrd_bwd: ', cngrd_bwd(8,1,1:4,1:4) !cl3293

      call conv_cgrid_bwd( cgrid_bwd, mdate, mtime, cngrd_bwd )
      !WRITE(*,*) 'in vdiff_bwd, after CALL conv_cgrid_bwd'
      !WRITE(*,*) 'cngrd_bwd: ', cngrd_bwd(7,1,1:4,1:4) !cl3293
      !WRITE(*,*) 'cngrd_bwd: ', cngrd_bwd(8,1,1:4,1:4) !cl3293


      end subroutine vdiff_bwd
