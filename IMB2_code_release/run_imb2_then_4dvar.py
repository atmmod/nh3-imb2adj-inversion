# =============================================================================
# Driver for the hybrid IMB2 + 4D-Var production run; a copy of
# py4dvar/tests/cris_obs_run_mb_4dvar.py (everything below this banner is
# unchanged). It runs IMB2 (main.mb_scal(); main = fourdvar._main_driver, see
# imb2_mb_scal.py), archives the IMB2 posterior, writes the IMB2 posterior
# emissions as the template (prior) emissions for 4D-Var, and then runs the
# 4D-Var minimizer (main.get_answer()). `context` is py4dvar/tests/context.py,
# which adds the py4dvar root directory to sys.path.
# =============================================================================
import os
import numpy as np
import context
import fourdvar.datadef as d
from fourdvar._transform import transform
from fourdvar._transform import transform_mb
import fourdvar.user_driver as user
import fourdvar._main_driver as main
import fourdvar.util.archive_handle as archive
import fourdvar.params.archive_defn as archive_defn
import fourdvar.util.cmaq_handle as cmaq
import setup_logging
logger = setup_logging.get_logger( __file__ )
import fourdvar.util.date_handle as dt
import fourdvar.params.cmaq_config as cmaq_config
import fourdvar.params.template_defn as template
import fourdvar.util.file_handle as fh
import fourdvar.util.netcdf_handle as ncf

# If rerunning after template emissions being replaced by MB posterior
# I have to regenerate tempalte emissions using MB prior NEI17 emissions
# copy prior NEI17 emissions into the cmaq_config.emis_file location
# and run the following code
# create record for emis files
#comment out if not rerunning after template emissions being replaced by MB posterior
for date in dt.get_datelist_bwd():
    emis_src = dt.replace_date( cmaq_config.emis_file, date )
    emis_dst = dt.replace_date( template.emis, date )
    fh.ensure_path( os.path.dirname( emis_dst ) )
    ncf.copy_compress( emis_src, emis_dst )
logger.info( 'template emissions regenerated by MB prior NEI17 emissions' )
#comment out if not rerunning after template emissions being replaced by MB posterior

# replace archive directory name and desciption file
archive_defn.experiment = 'cris_obs_run'
archive_defn.description = """real CrIS obs v1.6.3 assimilation"""

#SHORTLN/archive/cris_obs_run
cris_obs_avg_tot_col_archive = 'cris_obs_avg_tot_col.pic.gz' #Omega_o_bar
cris_obs_avg_prof_archive = 'cris_obs_avg_prof.pic.gz' 
post_mb_archive = 'post_mb.ncf' #pending

#get obs locations, weights and offsets
obs_shell = user.get_observed()
obs_tot_col_shell = user.get_observed_tot_col()
obs_avg_tot_col_shell = user.get_observed_avg_tot_col()
obs_avg_shell = user.get_observed_avg()

#generate observations
cris_obs_prof = obs_shell
cris_obs_tot_col = transform( cris_obs_prof, d.ObservationData_tot_col )  #retv_2_tot_col
cris_obs_avg_tot_col = transform( cris_obs_tot_col, d.ObservationData_avg_tot_col )  #avg_tot_col
#cris_obs_tot_col = obs_tot_col_shell
#cris_obs_avg_tot_col = obs_avg_tot_col_shell
cris_obs_avg_prof = obs_avg_shell

cris_obs_avg_tot_col.archive( cris_obs_avg_tot_col_archive ) #cris average total column observation #pending, ok
cris_obs_avg_prof.archive( cris_obs_avg_prof_archive ) #cris observation averaged if in same grid cell

cmaq.wipeout() #delete all files created by a run of cmaq, ok

##########################################################################################
#print cris observations mean value
o_val = cris_obs_prof.get_vector() #return the values of ObservationData as a 1D numpy array -->output: np.ndarray
o_avg_val = cris_obs_avg_prof.get_vector() #return the values of ObservationData as a 1D numpy array -->output: np.ndarray
o_tot_col_val = cris_obs_tot_col.get_vector() #return the values of ObservationData as a 1D numpy array -->output: np.ndarray
o_avg_tot_col_val = cris_obs_avg_tot_col.get_vector() #return the values of ObservationData as a 1D numpy array -->output: np.ndarray

logger.info( 'o_val.mean = {:}'.format( np.nanmean(o_val) ) )# ok
logger.info( 'o_avg_val.mean = {:}'.format( np.nanmean(o_avg_val) ) )# ok
logger.info( 'o_tot_col_val.mean = {:}'.format( np.nanmean(o_tot_col_val) ) )# ok
logger.info( 'o_avg_tot_col_val.mean = {:}'.format( np.nanmean(o_avg_tot_col_val) ) )# ok

logger.info( 'No. retrieval obs = {:}'.format( o_val.size ) )# ok
logger.info( 'No. avg retrieval obs = {:}'.format( o_avg_val.size ) )# ok
logger.info( 'No. total column obs = {:}'.format( o_tot_col_val.size ) )# ok
logger.info( 'No. avg. total columns obs = {:}'.format( o_avg_tot_col_val.size ) )# ok

##########################################################################################
#prepare inputs for the MB
obs_avg_tot_col_path = os.path.join( archive.get_archive_path(), cris_obs_avg_tot_col_archive ) #cris observation, pending
user.observed_avg_tot_col = d.ObservationData_avg_tot_col.from_file( obs_avg_tot_col_path ) #create an ObservationData from a file -->input: user-defined -->output: ObservationData , pending
obs_avg_path = os.path.join( archive.get_archive_path(), cris_obs_avg_prof_archive ) #cris observation averaged if in same grid cell
user.observed_avg = d.ObservationData_avg.from_file( obs_avg_path ) #for calculating cost function value

#run MB
logger.info( 'Start MB emission scaling' )
phy_post_mb = main.mb_scal()
phy_post_mb.archive( post_mb_archive )
logger.info( 'MB finished, result archived' )

##########################################################################################
#overwrite template emissions by MB posterior
emis_post_mb = transform( phy_post_mb, d.ModelInputData )  #prepare_mode:: proportional emission factors * template_emis, which is prior NEI emission

#save newly generated MB posterior emissions files as new template emissions for 4dvar
# create record for emis files
for date in dt.get_datelist_bwd():
    emis_src = dt.replace_date( cmaq_config.emis_file, date )
    emis_dst = dt.replace_date( template.emis, date )
    fh.ensure_path( os.path.dirname( emis_dst ) )
    ncf.copy_compress( emis_src, emis_dst )
    
logger.info( 'template emissions replaced by MB posterior' )

##########################################################################################
#run 4DVar minimizer
logger.info( 'Start py4dvar minimizer loop' )
main.get_answer() #run the minimizer & display results from user_driver module:
logger.info( 'py4dvar finished' )
